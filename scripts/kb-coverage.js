'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { loadCorpus } = require('../src/services/kbValidation');

function validateQuestions(bank, articles) {
  if (bank.status !== 'draft_labels' || !Array.isArray(bank.cases) || !bank.cases.length) throw new Error('Invalid question bank');
  const ids = new Set();
  const questions = new Set();
  const byId = new Map(articles.map(a => [a.id, a]));
  const covered = new Set();
  const actions = ['answer_with_evidence', 'clarify', 'escalate', 'fallback', 'decline_action', 'out_of_scope'];
  for (const c of bank.cases) {
    if (!c.id || ids.has(c.id) || typeof c.question !== 'string' || !c.question.trim()) throw new Error('Invalid or duplicate case');
    const key = JSON.stringify([c.history, c.question.trim().toLowerCase()]);
    if (questions.has(key)) throw new Error('Duplicate question and history');
    ids.add(c.id); questions.add(key);
    if (!['development', 'reserved'].includes(c.split) || !['en', 'sw', 'mixed'].includes(c.language) || !actions.includes(c.expected_action)) throw new Error('Invalid label');
    if (!Array.isArray(c.history) || c.history.some(h => !['user', 'assistant'].includes(h.role) || typeof h.text !== 'string')) throw new Error('Invalid history');
    if (!c.expected_behavior || !Array.isArray(c.must_not) || !c.must_not.length || !Array.isArray(c.target_article_ids) || !Array.isArray(c.required_claim_ids)) throw new Error('Missing expectations');
    for (const id of c.target_article_ids) {
      if (!byId.has(id)) throw new Error('Unknown target');
      if (c.expected_action === 'answer_with_evidence' && byId.get(id).visibility !== 'public') throw new Error('Answer targets internal content');
      covered.add(id);
    }
    for (const ref of c.required_claim_ids) {
      const [id, claim, extra] = ref.split(':');
      if (extra || !c.target_article_ids.includes(id) || !byId.get(id)?.claims.some(x => x.id === claim)) throw new Error('Unknown claim reference');
      if (c.expected_action === 'answer_with_evidence' && byId.get(id).claims.find(x => x.id === claim).evidence_status !== 'supported') throw new Error('Answer cites unresolved evidence');
    }
    if (c.expected_action === 'answer_with_evidence' && !c.required_claim_ids.length) throw new Error('Answer lacks evidence labels');
  }
  if (articles.some(a => !covered.has(a.id))) throw new Error('Service lacks question coverage');
  if (!bank.cases.some(c => c.split === 'reserved') || !bank.cases.some(c => c.split === 'development')) throw new Error('Missing evaluation split');
}

function report(bank, articles, sources) {
  validateQuestions(bank, articles);
  const lines = ['# KB coverage checkpoint', '', 'Generated by `npm run kb:coverage -- --write`. This is an editorial inventory, not an accuracy score or certification of completeness.', '',
    `${articles.length} articles; ${sources.length} sources; ${sources.filter(s => s.review_status === 'inspected').length} sources inspected to the extent recorded in their notes.`, '',
    `${bank.cases.length} authored questions: ${bank.cases.filter(c => c.split === 'development').length} development and ${bank.cases.filter(c => c.split === 'reserved').length} reserved. No model has been evaluated against them.`, '',
    `${articles.filter(a => a.status === 'approved').length} approved articles. Draft content cannot supply public answers.`, '',
    '| Service | Claims | Questions | Claim types absent (review prompts, not automatic requirements) |', '| --- | ---: | ---: | --- |'];
  for (const a of articles) {
    const missing = ['requirement', 'step', 'fee', 'timeline', 'exception', 'contact'].filter(k => !a.claims.some(c => c.kind === k));
    lines.push(`| ${a.id} | ${a.claims.length} | ${bank.cases.filter(c => c.target_article_ids.includes(a.id)).length} | ${missing.join(', ') || 'None; completeness still requires review'} |`);
  }
  lines.push('', '## Unresolved review work', '', 'Absent claim types may be inapplicable; a reviewer must decide. Presence of a claim does not establish complete coverage. Scope, eligibility, evidence, fees, timings, exceptions and contact routes all need service-level review.', '');
  for (const a of articles) {
    lines.push(`### ${a.title}`, '', ...a.unresolved_questions.map(q => `- ${q}`), '');
  }
  lines.push('## Evaluation readiness', '', `${bank.cases.filter(c => c.expected_action === 'answer_with_evidence' && !c.required_claim_ids.length).length} answer cases still need explicit claim-level expected evidence. These are design examples, not release tests.`, '', 'Reserved examples must stay out of prompts and retrieval content. Fluent reviewers must approve Kiswahili and mixed-language wording. Validate expected actions and citations before measuring the future engine.', '');
  return lines.join('\n');
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const { articles, sources } = loadCorpus(path.join(root, 'knowledge-base'));
  const bank = JSON.parse(fs.readFileSync(path.join(root, 'evaluation/kb/questions.json'), 'utf8'));
  const output = report(bank, articles, sources);
  if (process.argv.includes('--write')) fs.writeFileSync(path.join(root, 'docs/kb-coverage-report.md'), output);
  console.log(output);
}
module.exports = { validateQuestions, report };
